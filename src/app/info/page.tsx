export const metadata = { title: 'Помощь и информация' };
export default async function Page({
  searchParams,
}: {
  searchParams: Promise<{ section?: string }>;
}) {
  const { section = 'about' } = await searchParams;
  const localizedPages = information(await getLocale(), pages);
  const page = localizedPages[section] || localizedPages.about;
  const settings =
    section === 'contact'
      ? await db.setting.findMany({ where: { key: { in: ['contactEmail', 'contactPhone'] } } })
      : [];
  return (
    <div className="container section info-page">
      <span className="eyebrow">KIXO / GOOD TO KNOW</span>
      <h1>{page.title}</h1>
      <div className="account-layout">
        <nav className="account-nav">
          {Object.entries(localizedPages).map(([key, p]) => (
            <Link key={key} href={'/info?section=' + key}>
              {p.title}
            </Link>
          ))}
        </nav>
        <article>
          {page.text.map((p) => (
            <p key={p}>{p}</p>
          ))}
          {settings.map((s) => (
            <p key={s.key}>
              <strong>{s.key === 'contactEmail' ? 'Email' : 'Телефон'}:</strong> {s.value}
            </p>
          ))}
        </article>
      </div>
    </div>
  );
}
